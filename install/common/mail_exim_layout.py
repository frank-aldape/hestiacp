"""Stage wrapper or Debian-generated Exim configurations without changing live files."""
from pathlib import Path
import re

from mail_security_config import redirect_include


def normalized(content):
    # update-exim4.conf may strip comments and blank lines, but preserve directives.
    return '\n'.join(line.rstrip() for line in content.decode().splitlines()
                     if line.strip() and not line.lstrip().startswith('#'))


class EximLayout:
    def __init__(self, active, template, run,
                 generated=Path('/var/lib/exim4/config.autogenerated')):
        self.wrapper, self.template, self.run = Path(active), Path(template), run
        self.generated = Path(generated)
        self.debconf = self.template.parent / 'update-exim4.conf.conf'
        self.macros = self.template.parent / 'exim4.conf.localmacros'

    def layout(self):
        if self.wrapper.is_symlink() or self.template.is_symlink():
            raise ValueError('Symlinked Exim configuration requires manual review')
        if self.wrapper.exists():
            redirect_include(self.wrapper.read_text(), self.template, self.template)
            return 'wrapper', self.wrapper
        if self.generated.is_symlink() or self.debconf.is_symlink() or self.macros.is_symlink():
            raise ValueError('Symlinked Exim configuration requires manual review')
        if not self.generated.is_file() or not self.template.is_file():
            raise ValueError('Exim generated configuration or template is missing')
        split = re.findall(r"^[ \t]*dc_use_split_config[ \t]*=[ \t]*['\"]?(true|false)['\"]?[ \t]*$",
                           self.debconf.read_text(), re.M)
        if split != ['false']:
            raise ValueError('Only the unsplit Debian Exim template is supported')
        return 'generated', self.generated

    def prepare(self, candidate, stage):
        mode, active = self.layout()
        paths = [self.wrapper, self.template]
        if mode == 'generated':
            paths += [active, self.debconf, self.macros]
        self.before = {path: path.read_bytes() if path.exists() else None for path in paths}
        self.mode, self.active = mode, active
        self.metadata = active.stat()
        (stage / 'active-before').write_bytes(self.before[active])
        output = stage / 'config-candidate'
        if mode == 'wrapper':
            output.write_text(redirect_include(self.before[active].decode(), self.template,
                                               stage / 'candidate'))
        else:
            inputs = stage / 'generator-inputs'
            inputs.mkdir(mode=0o700)
            (inputs / 'conf.d').mkdir(mode=0o700)
            for path in (self.template, self.debconf, self.macros):
                if self.before[path] is not None:
                    (inputs / path.name).write_bytes(self.before[path])
            baseline = stage / 'config-baseline'
            self.generate(inputs, baseline)
            if normalized(baseline.read_bytes()) != normalized(self.before[active]):
                raise ValueError('Generated Exim configuration differs from its current inputs; '
                                 'review it before applying changes')
            (inputs / self.template.name).write_bytes(candidate)
            self.generate(inputs, output)
        self.assert_unchanged()
        return output

    def generate(self, inputs, output):
        self.run(['update-exim4.conf', '--confdir', str(inputs), '--output', str(output)])
        if not output.is_file():
            raise ValueError('Exim generator did not produce a candidate')

    def assert_unchanged(self):
        for path, previous in self.before.items():
            if path.is_symlink() or (path.read_bytes() if path.exists() else None) != previous:
                raise ValueError('Exim configuration changed during validation; reload the page')

    def verify_installed(self, candidate):
        mode, active = self.layout()
        if mode != self.mode or active != self.active:
            raise ValueError('Exim configuration layout changed during reload')
        if mode == 'generated' and normalized(active.read_bytes()) != normalized(candidate.read_bytes()):
            raise ValueError('Exim reload did not retain the validated generated configuration')
